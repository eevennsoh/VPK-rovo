function pickCollaborators(offset: number): readonly DemoTemplateCollaborator[] {
	return [0, 1, 2].map((step) => PEOPLE[(offset + step) % PEOPLE.length]);
}

function defaultCapabilities(name: string, description: string): readonly string[] {
	const lowerDescription = description.replace(/\.$/u, "").toLowerCase();

	return [
		description,
		`Pulls the context ${name} needs before drafting output.`,
		"Highlights risks, owners, gaps, and next steps.",
		"Links recommendations back to source work and docs.",
		"Formats results for quick review in team rituals.",
		"Keeps the workflow reusable for future runs.",
		lowerDescription.startsWith("turn") ? "Packages the result into a shareable brief." : `Helps teams ${lowerDescription}.`,
	];
}

function demoTemplateAgent({
	id,
	categoryId,
	name,
	description,
	avatarSrc,
	publisher,
	attributionKind = "team",
	verified = false,
	sources,
	skills,
	capabilities,
	remix,
	updated,
	peopleOffset,
	collaboratorOverflow = 3,
}: DemoTemplateConfig): AgentTemplatesAgent {
	return {
		id,
		categoryId,
		name,
		byline: `${name} by ${publisher}`,
		publisher,
		attributionKind,
		avatarSrc,
		description,
		verified,
		capabilities: capabilities ?? defaultCapabilities(name, description),
		sources: sources ?? CATEGORY_DEFAULTS[categoryId].sources,
		skills: skills ?? CATEGORY_DEFAULTS[categoryId].skills,
		stats: [
			{ label: "Remix", value: remix },
			{ label: "Last update", value: updated },
		],
		collaborators: pickCollaborators(peopleOffset),
		collaboratorOverflow,
	};
}

