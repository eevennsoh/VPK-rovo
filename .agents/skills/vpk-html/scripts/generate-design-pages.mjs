function readJson(filePath) {
	return JSON.parse(fs.readFileSync(filePath, "utf8"));
}

function htmlFilesIn(directory) {
	return fs.readdirSync(directory)
		.filter(file => file.endsWith(".html"))
		.sort((a, b) => a.localeCompare(b))
		.map(file => path.join(directory, file));
}

function stripEnhancement(html) {
	const pattern = new RegExp(`${escapeRegExp(ENHANCE_START)}[\\s\\S]*?${escapeRegExp(ENHANCE_END)}\\s*`, "gi");
	return html.replace(pattern, "");
}

function stripScripts(html) {
	return html.replace(/<script\b[\s\S]*?<\/script>/gi, "");
}

function styleBlocks(html) {
	return [...html.matchAll(/<style\b[^>]*>([\s\S]*?)<\/style>/gi)].map(match => match[1]);
}

function escapeRegExp(value) {
	return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function escapeHtml(value) {
	return String(value)
		.replace(/&/g, "&amp;")
		.replace(/</g, "&lt;")
		.replace(/>/g, "&gt;")
		.replace(/"/g, "&quot;");
}

function escapeAttr(value) {
	return escapeHtml(value)
		.replace(/#/g, "&#35;")
		.replace(/\(/g, "&#40;")
		.replace(/\)/g, "&#41;");
}

function safeValueHtml(value) {
	return escapeHtml(value)
		.replace(/#/g, "&#35;")
		.replace(/\b(rgba?|hsla?)\(/gi, "$1&#40;");
}

function slugify(value) {
	return value.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
}

function semanticMap(tokens) {
	const out = new Map();
	for (const [name, value] of Object.entries(tokens.semantic ?? {})) {
		const cssName = name === "shadow" ? "--shadow" : cssVarName(name);
		out.set(cssName, { semantic: name, value });
	}
	return out;
}

function containsRawColor(value) {
	return /#[0-9A-Fa-f]{3,8}\b|\b(?:rgb|rgba|hsl|hsla)\(/.test(value);
}

function isSolidHex(value) {
	return /^#[0-9A-Fa-f]{6}$/.test(value.trim());
}

function normalizeCssValue(value) {
	return value.trim().replace(/\s+/g, " ");
}

function collectTokenCatalog(demoFiles, tokens) {
	const semantic = semanticMap(tokens);
	const tokenRecords = new Map();
	const valueMap = new Map();
	const fileSources = new Map();
	const cssVarPattern = /(--[\w-]+)\s*:\s*([^;{}]+);/g;

	for (const filePath of demoFiles) {
		const file = path.basename(filePath);
		const html = stripEnhancement(fs.readFileSync(filePath, "utf8"));
		const usedInFile = new Set([...html.matchAll(/--[\w-]+/g)].map(match => match[0]));
		for (const name of usedInFile) {
			if (!fileSources.has(name)) fileSources.set(name, new Set());
			fileSources.get(name).add(file);
		}
		for (const css of styleBlocks(html)) {
			let match;
			while ((match = cssVarPattern.exec(css)) !== null) {
				const name = match[1];
				const value = normalizeCssValue(match[2]);
				if (!tokenRecords.has(name)) {
					tokenRecords.set(name, {
						name,
						values: new Map(),
						files: new Set(),
					});
				}
				const record = tokenRecords.get(name);
				record.values.set(value, (record.values.get(value) ?? 0) + 1);
				record.files.add(file);
				valueMap.set(name, value);
				if (!fileSources.has(name)) fileSources.set(name, new Set());
				fileSources.get(name).add(file);
			}
		}
	}

	for (const [name, entry] of semantic.entries()) {
		if (!tokenRecords.has(name)) {
			tokenRecords.set(name, {
				name,
				values: new Map([[entry.value, 1]]),
				files: new Set(),
			});
		}
		valueMap.set(name, entry.value);
	}

	function resolveHex(value, seen = new Set()) {
		const normalized = value.trim();
		if (isSolidHex(normalized)) return normalized.toLowerCase();
		const reference = normalized.match(/^var\((--[\w-]+)\)$/);
		if (!reference || seen.has(reference[1])) return null;
		seen.add(reference[1]);
		const next = valueMap.get(reference[1]) ?? semantic.get(reference[1])?.value;
		return next ? resolveHex(next, seen) : null;
	}

	return [...tokenRecords.values()]
		.map(record => {
			const semanticEntry = semantic.get(record.name) ?? null;
			const values = [...record.values.entries()].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]));
			const value = semanticEntry?.value ?? values[0]?.[0] ?? "";
			const files = fileSources.get(record.name) ?? record.files;
			const colorHex = resolveHex(value);
			return {
				...record,
				value,
				colorHex,
				group: groupToken(record.name, semanticEntry?.semantic ?? ""),
				semantic: semanticEntry?.semantic ?? "",
				fileCount: files.size,
				valueCount: values.length,
			};
		})
		.sort((a, b) => GROUPS.findIndex(([id]) => id === a.group) - GROUPS.findIndex(([id]) => id === b.group) || a.name.localeCompare(b.name));
}

function groupToken(name, semantic) {
	const haystack = `${name} ${semantic}`.toLowerCase();
	if (/(paper|surface|background|overlay|sunken|raised|white|ivory|shadow)/.test(haystack)) return "paper-surfaces";
	if (/(text|ink|headline|muted|subtlest|inverse|meta|review|slate|gray|near-black)/.test(haystack)) return "text";
	if (/(accent|brand|primary|link|collection|clay|oat|olive|rust|sky|selected)/.test(haystack)) return "accents";
	if (/(rule|border|divider|stroke|frame)/.test(haystack)) return "rules-borders";
	if (/(chip|pill|badge|tag)/.test(haystack)) return "chips-pills";
	if (/table/.test(haystack)) return "tables";
	if (/(chart|heat|diff|success|warning|danger|info|syntax|math)/.test(haystack)) return "charts-heat";
	if (/(ill-|illustration|hatch|guide|focal)/.test(haystack)) return "illustration";
	if (/(focus|search|ease|dur|motion|stagger|enter|hover|pressed)/.test(haystack)) return "focus-interaction";
	if (/(font|type|mono|sans|serif|display|numeric|page|pad|radius|space|gap|width|height|size)/.test(haystack)) return "spacing-typography";
	return "other";
}

function cssDefinitionsForCatalog(tokens, semantic) {
	const lines = [":root {"];
	for (const token of tokens) {
		if (semantic.has(token.name)) continue;
		if (!token.value || token.value.includes("{") || token.value.includes("}")) continue;
		if (containsRawColor(token.value)) continue;
		lines.push(`\t${token.name}: ${token.value};`);
	}
	lines.push("}");
	return lines.length > 2 ? lines.join("\n") : "";
}

function colorLike(token) {
	return Boolean(token.colorHex) || /^var\(--[\w-]+\)$/.test(token.value) || containsRawColor(token.value);
}

function tokenRow(token) {
	const isColor = colorLike(token);
	const editor = token.colorHex
		? `<input class="vpkh-token-color" type="color" value="${escapeAttr(token.colorHex)}" data-token-input aria-label="Edit ${escapeAttr(token.name)}">`
		: `<input class="vpkh-token-text" type="text" value="${escapeAttr(token.value)}" data-token-input aria-label="Edit ${escapeAttr(token.name)}">`;
	const preview = isColor
		? `<span class="vpkh-swatch" style="background: var(${token.name}, var(--surface-sunken));"></span>`
		: `<span class="vpkh-value-preview">${safeValueHtml(token.value)}</span>`;
	const semantic = token.semantic ? `<span>${escapeHtml(token.semantic)}</span>` : `<span class="vpkh-muted">unmapped</span>`;
	const variants = token.valueCount > 1 ? `<span class="vpkh-muted">+${token.valueCount - 1} scoped</span>` : `<span class="vpkh-muted">single</span>`;
	return `<article class="vpkh-token-row" data-token-row data-token="${escapeAttr(token.name)}" data-default="${escapeAttr(token.value)}" data-color-default="${escapeAttr(token.colorHex ?? "")}">
	<div class="vpkh-token-preview">${preview}</div>
	<div class="vpkh-token-name"><code>${escapeHtml(token.name)}</code></div>
	<div class="vpkh-token-value"><code>${safeValueHtml(token.value)}</code>${variants}</div>
	<div class="vpkh-token-semantic">${semantic}</div>
	<div class="vpkh-token-count">${token.fileCount} files</div>
	<div class="vpkh-token-editor">${editor}</div>
</article>`;
}

function tokenSections(tokens) {
	return GROUPS.map(([id, label]) => {
		const groupTokens = tokens.filter(token => token.group === id);
		if (groupTokens.length === 0) return "";
		return `<section class="vpkh-section" id="tokens-${id}">
	<div class="vpkh-section-head">
		<p>${String(groupTokens.length).padStart(2, "0")}</p>
		<h2>${label}</h2>
	</div>
	<div class="vpkh-token-table" role="table" aria-label="${escapeAttr(label)} tokens">
		<div class="vpkh-token-header" role="row">
			<span>Preview</span>
			<span>Variable</span>
			<span>Current value</span>
			<span>Semantic</span>
			<span>Coverage</span>
			<span>Editor</span>
		</div>
		${groupTokens.map(tokenRow).join("\n\t\t")}
	</div>
</section>`;
	}).filter(Boolean).join("\n");
}

