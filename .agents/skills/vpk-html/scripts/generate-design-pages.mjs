function writeIfChanged(filePath, html) {
	const before = fs.existsSync(filePath) ? fs.readFileSync(filePath, "utf8") : "";
	if (before === html) return false;
	fs.writeFileSync(filePath, html);
	return true;
}

function existingEnhancementBlock(filePath) {
	if (!fs.existsSync(filePath)) return "";
	const html = fs.readFileSync(filePath, "utf8");
	const pattern = new RegExp(`${escapeRegExp(ENHANCE_START)}[\\s\\S]*?${escapeRegExp(ENHANCE_END)}`, "i");
	return html.match(pattern)?.[0] ?? "";
}

function withExistingEnhancement(html, block) {
	if (!block) return html;
	return html.replace(/<\/body>/i, `${block}\n</body>`);
}

function main() {
	const tokens = readJson(TOKENS_FILE);
	const demoFiles = htmlFilesIn(DEMOS);
	const semantic = semanticMap(tokens);
	const tokenCatalog = collectTokenCatalog(demoFiles, tokens);
	const patterns = collectClassCatalog(demoFiles);
	const designHtml = withExistingEnhancement(buildDesignPage(tokenCatalog, demoFiles.length, semantic), existingEnhancementBlock(DESIGN_PAGE));
	const variantsHtml = withExistingEnhancement(buildVariantsPage(patterns, demoFiles.length), existingEnhancementBlock(VARIANTS_PAGE));
	const designChanged = writeIfChanged(DESIGN_PAGE, designHtml);
	const variantsChanged = writeIfChanged(VARIANTS_PAGE, variantsHtml);
	console.log(`vpkh design pages generated: tokens=${tokenCatalog.length} patterns=${patterns.length} designChanged=${designChanged} variantsChanged=${variantsChanged}`);
}

main();
